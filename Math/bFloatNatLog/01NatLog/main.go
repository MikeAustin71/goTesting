  // term1 = π / (2 * AGM)
  denom := new(big.Float).SetPrec(workPrec).SetMode(big.AwayFromZero)
  denom.Mul(two, AGM)

  term1 := new(big.Float).SetPrec(workPrec).SetMode(big.AwayFromZero)
  term1.Quo(pi, denom)

  // term2 = (k - 2) * ln(2)
  kAdj := big.NewInt(int64(k - 2))
  kFloat := new(big.Float).SetPrec(workPrec).SetMode(big.AwayFromZero).SetInt(kAdj)

  term2 := new(big.Float).SetPrec(workPrec).SetMode(big.AwayFromZero)
  term2.Mul(kFloat, ln2)

  // ln(x) = term1 + term2
  lnxWork := new(big.Float).SetPrec(workPrec).SetMode(big.AwayFromZero)
  lnxWork.Add(term1, term2)

  // Return result at requested precision
