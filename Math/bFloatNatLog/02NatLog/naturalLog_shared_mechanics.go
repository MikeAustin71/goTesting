var (
	lenEulersNumberStr              int
	lenPiNumberStr                  int
	lenNatLogNumberStr              int
	eulersNumBaseFull               *big.Float
	piFull                          *big.Float
	ln2Full                         *big.Float
	DEFAULT_BASE_NUM_DECIMAL_DIGITS uint
)

func init() {

	lenEulersNumberStr = len(eulersConstNumStr)

	lenPiNumberStr = len(pi20kDigitStr)

	lenNatLogNumberStr = len(natLog2Str20kDigits)

	DEFAULT_BASE_NUM_DECIMAL_DIGITS = 0

	var constPrec uint

	var baseBits float64

	// Set eulers number with default Number of
	// decimal digits. 4000 decimal digits of accuracy.
	// Length of lenEulersNumberStr MUST BE >= 4000
	baseBits = (float64(4000) * 3.321928094887362) + 128.0

	constPrec = uint(math.Ceil(baseBits))

	eulersNumBaseFull = big.NewFloat(0)

	eulersNumBaseFull.
		SetMode(big.AwayFromZero).
		SetPrec(constPrec).
		SetString(eulersConstNumStr[:4002])

	// Set pi and natural log constants to 2000 decimal digits
	// of accuracy.
	baseBits = (float64(2000) * 3.321928094887362) + 128.0

	constPrec = uint(math.Ceil(baseBits))

	piFull = new(big.Float).
		SetPrec(constPrec).
		SetMode(big.AwayFromZero)
	piFull.SetString(pi20kDigitStr[:2002])

	ln2Full = new(big.Float).
		SetPrec(constPrec).
		SetMode(big.AwayFromZero)
	ln2Full.SetString(natLog2Str20kDigits[:2002])

}

// getEulersNum
//
//	Computes and returns the value of Euler's number to the
//	specified decimal digit precision as a big.Float.
func (nlSharedMech *naturalLogSharedMechanics) getEulersNum(decimalDigitsOfPrecision uint) *big.Float {

	// lenEulersNumberStr - 2 = 49,999
	if int(decimalDigitsOfPrecision) > (lenEulersNumberStr - 2) {

		decimalDigitsOfPrecision = uint(lenEulersNumberStr - 2)

	}

	if decimalDigitsOfPrecision == DEFAULT_BASE_NUM_DECIMAL_DIGITS {

		newEulersNumFull := new(big.Float).Copy(eulersNumBaseFull)

		return newEulersNumFull

	}

	prec := new(BigFloatHelper).ComputeBigFloatPrecisionBits(
		decimalDigitsOfPrecision, 1)

	eulersNumBaseCustom := big.NewFloat(0)

	eulersNumBaseCustom.
		SetMode(big.AwayFromZero).
		SetPrec(prec).
		SetString(eulersConstNumStr[:decimalDigitsOfPrecision+2])

	return eulersNumBaseCustom
}

// getPi
//
//			Returns the full-precision cached value of π.
//			Internal algorithms should always use this value directly.
//
//		 When the input parameter 'decimalDigitsOfPrecision' is set to
//		 zero (0), the default value of pi is returned to 2,000 digits
//		 of decimal precision.
//
//		 The maximum number of decimal digits of precision is limited to
//		 20,000.
//
//	  Note: DEFAULT_BASE_NUM_DECIMAL_DIGITS = 0
func (nlSharedMech *naturalLogSharedMechanics) getPi(decimalDigitsOfPrecision uint) *big.Float {

	if int(decimalDigitsOfPrecision) > (lenPiNumberStr - 2) {

		decimalDigitsOfPrecision = uint(lenPiNumberStr - 2)
	}

	if decimalDigitsOfPrecision == DEFAULT_BASE_NUM_DECIMAL_DIGITS {

		newPiNumFull := new(big.Float).Copy(piFull)

		return newPiNumFull
	}

	prec := new(BigFloatHelper).ComputeBigFloatPrecisionBits(
		decimalDigitsOfPrecision, 1)

	piNumBaseCustom := big.NewFloat(0)

	piNumBaseCustom.
		SetMode(big.AwayFromZero).
		SetPrec(prec).
		SetString(pi20kDigitStr[:decimalDigitsOfPrecision+2])

	return piNumBaseCustom
}

// getLn2
//
//	Computes and returns the value of ln(2) to the specified
//	decimal digit precision as a big.Float. ln(2) is the
//	natural log of 2.
//
//	When the input parameter 'decimalDigitsOfPrecision' is set to
//	zero (0), the default value of natural log of 2 is returned to
//	2,000 digits of decimal precision.
//
//	The maximum number of decimal digits of precision is limited to
//	20,000.
func (nlSharedMech *naturalLogSharedMechanics) getLn2(decimalDigitsOfPrecision uint) *big.Float {

	if int(decimalDigitsOfPrecision) > (lenNatLogNumberStr - 2) {

		decimalDigitsOfPrecision = uint(lenNatLogNumberStr - 2)
	}

	if decimalDigitsOfPrecision == DEFAULT_BASE_NUM_DECIMAL_DIGITS {

		newNatLog2Number := new(big.Float).Copy(ln2Full)

		return newNatLog2Number
	}

	ln2NumBaseCustom := big.NewFloat(0)

	prec := new(BigFloatHelper).ComputeBigFloatPrecisionBits(
		decimalDigitsOfPrecision, 1)

	ln2NumBaseCustom.
		SetMode(big.AwayFromZero).
		SetPrec(prec).
		SetString(natLog2Str20kDigits[:decimalDigitsOfPrecision+2])

	return ln2NumBaseCustom
}
