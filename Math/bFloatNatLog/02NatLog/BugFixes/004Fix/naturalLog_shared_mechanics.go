// Full-precision cached constants (loaded once).
var (
	piFull  *big.Float
	ln2Full *big.Float
)

// init loads piFull and ln2Full at full available precision (~7000 bits)
// from the 2,000-digit decimal strings. These values are never modified.
func init() {
	constPrec := uint(7000)

	piFull = new(big.Float).
		SetPrec(constPrec).
		SetMode(big.AwayFromZero)
	piFull.SetString(pi2kDigitStr)

	ln2Full = new(big.Float).
		SetPrec(constPrec).
		SetMode(big.AwayFromZero)
	ln2Full.SetString(natLog2Str2kDigits)
}

// getPi
//
//	Returns the full-precision cached value of π.
//	Internal algorithms should always use this value directly.
func (nlSharedMech *naturalLogSharedMechanics) getPi(prec uint) *big.Float {
	return piFull
}

// getLn2
//
//	Returns the full-precision cached value of ln(2).
//	Internal algorithms should always use this value directly.
func (nlSharedMech *naturalLogSharedMechanics) getLn2(prec uint) *big.Float {
	return ln2Full
}
